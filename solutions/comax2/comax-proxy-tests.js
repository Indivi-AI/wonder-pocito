Data('fetchComaxRanges', {
  params: [
    { id: 'sources', as: 'array', mandatory: true },
    { id: 'ranges', as: 'object', mandatory: true }
  ],
  impl: async (ctx, {}, { sources, ranges }) => {
    const Pool  = await import('undici')
    const pool = new Pool('http://localhost:3000')
    const at = performance.now(), plans = sources.map(({ wUrl, url }) => {
      const file = wUrl.split('/').pop()
      const requested = ranges[file].join(',').split(',').map(x => x.split(':').map(Number))
      const expectedBytes = requested.reduce((sum, [, length]) => sum + length, 0)
      const merged = requested
      const { pathname, search } = new URL(url)
      return { file, requested, expectedBytes, merged,
        path: `/gcs-proxy/range-stream-parallel${pathname}${search}${search ? '&' : '?'}packetSize=65536` }
    }), preparedAt = performance.now(), files = await Promise.all(plans.map(async ({ file, requested, expectedBytes, merged, path }) => {
      const { statusCode, body } = await pool.request({
        path, method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(merged)
      })
      if (statusCode !== 200) throw new Error(`${file}: proxy ${statusCode}`)
      let pending = Buffer.alloc(0), receivedBytes = 0
      for await (const chunk of body) {
        pending = Buffer.concat([pending, chunk])
        while (pending.length >= 12 && pending.length >= 12 + pending.readUInt32BE(8)) {
          const length = pending.readUInt32BE(8)
          receivedBytes += length
          pending = pending.subarray(12 + length)
        }
      }
      return { file, sourceRanges: requested.length, ranges: merged.length, expectedBytes, receivedBytes }
    }))
    const fetchedAt = performance.now()
    await pool.close()
    const closedAt = performance.now()
    const result = {
      files: files.length,
      sourceRanges: files.reduce((sum, file) => sum + file.sourceRanges, 0),
      ranges: files.reduce((sum, file) => sum + file.ranges, 0),
      expectedBytes: files.reduce((sum, file) => sum + file.expectedBytes, 0),
      receivedBytes: files.reduce((sum, file) => sum + file.receivedBytes, 0),
      prepareMs: preparedAt - at,
      fetchMs: fetchedAt - preparedAt,
      closeMs: closedAt - fetchedAt,
      ms: closedAt - at,
      byFile: files
    }
    ctx.vars.dbLogger?.info?.({ t: 'comax ranges fetched', ...result, byFile: undefined }, {}, { ctx })
    return result
  }
})

